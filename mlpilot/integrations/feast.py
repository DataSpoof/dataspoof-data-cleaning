"""Feast integration (needs ``feast``; the ``[feast]`` extra).

Start with the built-in :class:`~mlpilot.FeatureStore`, and move to Feast when you
need its online stores (Redis, DynamoDB, Bigtable, Postgres...), its feature server or its UI.
The export writes an ordinary Feast repository, so the ``feast`` CLI works on it:

>>> from mlpilot.integrations.feast import export_to_feast, feast_features
>>> fs = export_to_feast(store, "feast_repo", project="growth")     # feature_store.yaml + definitions, applied
>>> fs.get_historical_features(entity_df.to_pandas(), feast_features(store, ["customer_stats:*"])).to_df()
>>> fs.get_online_features(["customer_stats:spend_30d"], [{"customer_id": 42}]).to_dict()

What gets exported:

* ``feature_store.yaml``  local provider, file offline store, SQLite online store (edit it to
  point at your production stores; the definitions don't change).
* ``features.py``         Entities, FileSources and FeatureViews generated from the registry
  (types from the stored schema, TTL, description, owner, tags).
* ``data/<view>.parquet`` each view's full offline history (timestamps in UTC).

An entity with several join keys becomes one Feast entity per key (Feast entities have one key).
Point-in-time semantics match: feature timestamp <= entity timestamp, within the TTL (verified
value-for-value against Feast 0.67). One difference: Feast's *file* offline store can leave out
some entity rows that have no feature value inside the TTL window, while
``FeatureStore.get_historical_features`` keeps them with nulls so no labelled row is lost.
"""

from __future__ import annotations

import datetime as _dt
import runpy
from pathlib import Path

import polars as pl

try:
    import feast
except ImportError as exc:                                   # pragma: no cover
    raise ImportError('The Feast integration needs feast: pip install "mlpilot[feast]"') from exc

_FEAST_TYPES = {"Int8": "Int32", "Int16": "Int32", "Int32": "Int32", "Int64": "Int64", "UInt8": "Int32",
                "UInt16": "Int32", "UInt32": "Int64", "UInt64": "Int64", "Float32": "Float32", "Float64": "Float64",
                "String": "String", "Utf8": "String", "Categorical": "String", "Boolean": "Bool",
                "Date": "UnixTimestamp", "Binary": "Bytes"}
_VALUE_TYPES = {"Int64": "INT64", "Int32": "INT32", "String": "STRING", "Bytes": "BYTES", "Bool": "BOOL",
                "Float64": "DOUBLE", "Float32": "FLOAT", "UnixTimestamp": "UNIX_TIMESTAMP"}


def _feast_type(dtype: str | None) -> str:
    if not dtype:
        return "Float64"
    base = dtype.split("(")[0].split("[")[0]
    if base == "Datetime":
        return "UnixTimestamp"
    return _FEAST_TYPES.get(base, "String")


def _ident(name: str) -> str:
    out = "".join(c if c.isalnum() else "_" for c in name)
    return out if not out[0].isdigit() else f"_{out}"


def feast_features(store, refs: list) -> list:
    """Our feature references (``"view:feature"`` / ``"view:*"``) as Feast references."""
    out = []
    for ref in refs:
        view, feat = ref.split(":", 1)
        out += [f"{view}:{f}" for f in store.view(view).features] if feat == "*" else [ref]
    return out


def _yaml(project: str, online: str | None) -> str:
    online_block = online or "online_store:\n  type: sqlite\n  path: data/online_store.db\n"
    return (f"project: {project}\nregistry: data/registry.db\nprovider: local\n{online_block}"
            "offline_store:\n  type: file\nentity_key_serialization_version: 3\n")


def _definitions(store, views: list, data_dir: Path) -> str:
    reg = store._reg()
    lines = ['"""Feast definitions generated by mlpilot.integrations.feast - edit freely."""',
             "from datetime import timedelta", "",
             "from feast import Entity, FeatureView, Field, FileSource, ValueType",
             "from feast.types import Bool, Bytes, Float32, Float64, Int32, Int64, String, UnixTimestamp", ""]
    entity_vars: dict = {}
    used_entities = {e for v in views for e in reg["views"][v]["entities"]}
    for ename in sorted(used_entities):
        ent = reg["entities"][ename]
        keys = ent["join_keys"]
        some_view = next(reg["views"][v] for v in views if ename in reg["views"][v]["entities"])
        schema = some_view.get("schema") or {}
        entity_vars[ename] = []
        for key in keys:
            fname = ename if len(keys) == 1 else f"{ename}__{key}"
            var = _ident(f"entity_{fname}")
            vt = _VALUE_TYPES.get(_feast_type(schema.get(key)), "STRING")
            lines.append(f"{var} = Entity(name={fname!r}, join_keys=[{key!r}], value_type=ValueType.{vt}, "
                         f"description={ent.get('description') or ''!r})")
            entity_vars[ename].append(var)
    lines.append("")
    for vname in views:
        v = reg["views"][vname]
        schema = v.get("schema") or {}
        src = _ident(f"{vname}_source")
        path = (data_dir / f"{vname}.parquet").resolve().as_posix()
        lines.append(f"{src} = FileSource(name={vname + '_source'!r}, path={path!r}, "
                     f"timestamp_field={v['timestamp']!r})")
        ttl = f"timedelta(days={float(v['ttl_days'])!r})" if v.get("ttl_days") else "timedelta(0)"
        fields = ", ".join(f"Field(name={f!r}, dtype={_feast_type(schema.get(f))})" for f in v["features"])
        ents = ", ".join(var for e in v["entities"] for var in entity_vars[e])
        tags = {str(k): str(t) for k, t in (v.get("tags") or {}).items()}
        lines.append(f"{_ident(vname)} = FeatureView(\n    name={vname!r},\n    entities=[{ents}],\n"
                     f"    ttl={ttl},\n    schema=[{fields}],\n    online=True,\n    source={src},\n"
                     f"    description={v.get('description') or ''!r},\n    owner={v.get('owner') or ''!r},\n"
                     f"    tags={tags!r},\n)")
        lines.append("")
    return "\n".join(lines)


def export_to_feast(store, repo_dir, *, project: str = "mlpilot", views: list | None = None,
                    apply: bool = True, materialize: bool = True, online_store_yaml: str | None = None):
    """Write a Feast repository for ``store`` (all views, or ``views``), then optionally
    ``feast apply`` it and materialize the online store. Returns a ``feast.FeatureStore``.

    ``online_store_yaml`` replaces the default SQLite ``online_store:`` block, e.g.
    ``"online_store:\\n  type: redis\\n  connection_string: redis:6379\\n"``."""
    repo = Path(repo_dir)
    data = repo / "data"
    data.mkdir(parents=True, exist_ok=True)
    names = list(views) if views is not None else list(store._reg()["views"])
    if not names:
        raise ValueError("The feature store has no feature views to export")
    starts = []
    for vname in names:
        view = store.view(vname)
        hist = store._offline(vname).collect()
        ts = pl.col(view.timestamp)
        dtype = hist.schema[view.timestamp]
        if isinstance(dtype, pl.Datetime) and dtype.time_zone:
            hist = hist.with_columns(ts.dt.convert_time_zone("UTC"))
        else:
            hist = hist.with_columns(ts.cast(pl.Datetime("us")).dt.replace_time_zone("UTC"))
        hist.write_parquet(data / f"{vname}.parquet")
        starts.append(hist[view.timestamp].min())
    (repo / "feature_store.yaml").write_text(_yaml(project, online_store_yaml), encoding="utf-8")
    (repo / "features.py").write_text(_definitions(store, names, data), encoding="utf-8")
    fs = feast.FeatureStore(repo_path=str(repo))
    if apply:
        ns = runpy.run_path(str(repo / "features.py"))
        objs = [o for o in ns.values() if isinstance(o, (feast.Entity, feast.FeatureView))]
        fs.apply(objs)
        if materialize:
            start = min(s for s in starts if s is not None) - _dt.timedelta(seconds=1)
            fs.materialize(start_date=start, end_date=_dt.datetime.now(_dt.timezone.utc),
                           feature_views=names)
    return fs


def to_feast_entity_df(entity_df, timestamp: str = "event_timestamp"):
    """A pandas entity DataFrame Feast accepts (UTC timestamps in ``event_timestamp``)."""
    df = entity_df if isinstance(entity_df, pl.DataFrame) else pl.from_pandas(entity_df)
    ts = pl.col(timestamp)
    dtype = df.schema[timestamp]
    df = df.with_columns((ts.dt.convert_time_zone("UTC") if isinstance(dtype, pl.Datetime) and dtype.time_zone
                          else ts.cast(pl.Datetime("us")).dt.replace_time_zone("UTC")).alias("event_timestamp"))
    if timestamp != "event_timestamp":
        df = df.drop(timestamp)
    return df.to_pandas()
